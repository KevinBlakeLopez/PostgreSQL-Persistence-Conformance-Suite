"""Summarize every recorded run into outputs/SUMMARY.md.

  python -I summarize.py

One row per repetition, built only from each run's result.json. Runs that
ended with a harness error are listed too.
"""

import json
import sys
from pathlib import Path

OUTPUTS = Path(__file__).resolve().parent.parent / "outputs"


def held_count(sets):
    return sum(len(v) for v in (sets or {}).values())


def d4_row(r):
    markers = r.get("log_markers_worker1", {})
    return [
        str(r.get("message_lost", "")),
        str(r.get("retry_enqueued_by_worker")),
        str(r.get("original_settled_by", "")),
        " ".join("a%s" % a for a, _ in r.get("attempts_started", [])),
        str(len(r.get("places_final", []))),
        str(sum(len(v) for k, v in (r.get("dead_letter_keys") or {}).items() if k.endswith(".XQ"))),
        str(r.get("redelivered_to_replacement", "")),
        "%d/%d" % (markers.get("Retrying message", 0), markers.get("Unexpected failure in after_process_message", 0)),
        ",".join(r.get("actor_redis_write_failed", [])),
        str(r.get("completed", "")),
        ",".join(h.split(":")[-1] for p in r["places_after_final_redis_restart"] for h in p["held_by"]) or "none" if "places_after_final_redis_restart" in r else "-",
    ]


D4_HEAD = ["lost", "retry enqueued", "original settled by", "attempts", "places at end", "dead letters", "redelivered to replacement", "log: Retrying / Unexpected failure", "actor's own Redis error", "a task_done seen", "held by, after a final Redis restart"]


def n1_row(r):
    cps = r.get("checkpoints", [])
    stranded = [c for c in cps if c["still_in_worker1_dq_ack_set"]]
    ages = [c["worker1_heartbeat_age_ms"] for c in cps if c.get("worker1_heartbeat_age_ms") is not None]
    markers = r.get("log_markers_worker1_before_stop", {})
    return [
        str(len(r.get("held_by_worker1_before_fault", []))),
        str(len(r.get("executed_while_worker1_alive", []))),
        "%s s" % (max(c["seconds_after_first_eta"] for c in stranded) if stranded else "-"),
        "%s-%s ms" % (min(ages), max(ages)) if ages else "-",
        str(held_count(r.get("after_worker1_exit"))) if "after_worker1_exit" in r else "-",
        str(len(r.get("executed_by_replacement", []))) if "executed_by_replacement" in r else "-",
        str(markers.get("Consumer encountered a connection error", 0)),
    ]


N1_HEAD = ["held before fault", "executed while worker 1 alive", "last stranded checkpoint after ETA", "worker 1 heartbeat age", "still in worker 1 ack set after its exit", "executed by replacement", "log: connection errors"]


def n2_row(r):
    markers = r.get("log_markers_worker1", {})
    places = r.get("probe_delayed_places", [])
    return [
        str(r.get("pause_ms", "")),
        str(len(r.get("held_after_pause", []))),
        str(r.get("probe_now_executed")),
        str(r.get("probe_delayed_executed")),
        ",".join(h.split(":")[-1] for p in places for h in p["held_by"]) or "-",
        str(len(r.get("held_after_worker1_exit", []))),
        str(markers.get("Exception in thread", 0)),
        str(r.get("worker1_exit")),
    ]


N2_HEAD = ["pause ms", "held after pause", "ordinary probe ran", "delayed probe ran", "delayed probe held by", "held after worker 1 exit", "log: Exception in thread", "worker 1 exit"]


def d7_row(r):
    markers = r.get("log_markers_worker1", {})
    return [
        str(r.get("worker1_exit")),
        str(r.get("worker1_hung")),
        str(r.get("after_worker_shutdown_hook_ran")),
        str(held_count(r.get("held_before_requeue"))),
        str(held_count(r.get("held_after_exit"))),
        str(len(r.get("queue_after_exit", []))),
        str(len(r.get("executed_by_replacement", []))),
        str(r.get("recovery_seconds_after_replacement_boot", "")),
        "%d/%d" % (markers.get("Failed to requeue messages", 0), markers.get("Worker has been shut down", 0)),
    ]


D7_HEAD = ["worker 1 exit", "hung", "after_worker_shutdown ran", "held before requeue", "held after exit", "queue after exit", "executed by replacement", "recovery s", "log: Failed to requeue / shut down"]

TABLES = {"d4": (D4_HEAD, d4_row), "n1": (N1_HEAD, n1_row), "n2": (N2_HEAD, n2_row), "d7": (D7_HEAD, d7_row)}


def main():
    lines = ["# Summary of recorded runs", "", "Generated by `reproductions/summarize.py` from each run's `result.json`.", ""]
    sections = [(platform, experiment, root / experiment) for platform, root in (("macOS", OUTPUTS), ("Linux", OUTPUTS / "linux")) for experiment in TABLES]
    for platform, experiment, base in sections:
        head, row = TABLES[experiment]
        if not base.exists():
            continue
        lines += ["## %s (%s)" % (experiment.upper(), platform), ""]
        for variant in sorted(p for p in base.iterdir() if p.is_dir()):
            runs = sorted(variant.glob("*/result.json"))
            lines += ["### %s (%d runs)" % (variant.name, len(runs)), ""]
            lines += ["| run | build | " + " | ".join(head) + " |", "| --- | --- | " + " | ".join("---" for _ in head) + " |"]
            for path in runs:
                r = json.loads(path.read_text())
                build = r.get("environment", {}).get("dramatiq_build", "?")
                if r.get("harness_error"):
                    lines.append("| %s | %s | harness error: %s |" % (path.parent.name, build, r["harness_error"].replace("|", "/")))
                    continue
                lines.append("| %s | %s | %s |" % (path.parent.name, build, " | ".join(row(r))))
            lines.append("")
    text = "\n".join(lines) + "\n"
    (OUTPUTS / "SUMMARY.md").write_text(text)
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
