// Derives the result matrix from a recorded run. Reads <run dir>/runs.json and writes matrix.json and
// matrix.md beside it. Every value comes from a recorded field, named in FIELDS below. The output has no
// timestamp, so running this again on the same runs.json gives byte-identical files.
//
//   node summarize.mjs ../output/<run id>

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = process.argv[2]
if (!dir) throw new Error('usage: node summarize.mjs <run dir>')
const recorded = JSON.parse(readFileSync(join(dir, 'runs.json'), 'utf8'))

const FIELDS = {
  inner_writes: 'final.markers (connection opened after the subject exited): "persisted" if it holds "inner", "rolled back" if the subject wrote "inner" and it is absent',
  inner_after_rollback: 'final.sink: the sink row afterRollBack:inner, written by its own autocommit connection',
  inner_after_commit: 'final.sink: the sink row afterCommit:inner',
  outer_transaction_server: 'transactions (performance_schema.events_transactions_history_long for the subject thread): STATE of the first transaction with AUTOCOMMIT NO',
  outer_api: 'result.steps["main"]: whether the outer completion call returned or raised, and the class',
  rollback_to_savepoint_sent: 'statements (events_statements_history_long for the subject thread): any statement/sql/rollback_to_savepoint, with its MYSQL_ERRNO',
  laravel_level: 'checkpoint after-error, step main and checkpoint final: Connection::transactionLevel() as the subject reported it',
  manager_pending_after_end: 'checkpoint after-end: levels of DatabaseTransactionsManager::getPendingTransactions()',
  sink_final: 'final.sink in insertion order',
}

const rows = recorded.runs.map((run) => derive(run))
const groups = new Map()
for (const row of rows) {
  const key = `${row.scenario} ${row.server}`
  if (!groups.has(key)) groups.set(key, [])
  groups.get(key).push(row)
}
const matrix = [...groups.values()].map((group) => {
  const out = { scenario: group[0].scenario, server: group[0].server, repetitions: group.length, matched_expectation: group.filter((row) => row.matched).length }
  for (const field of Object.keys(FIELDS)) {
    const values = [...new Set(group.map((row) => JSON.stringify(row[field])))].map((text) => JSON.parse(text))
    out[field] = values.length === 1 ? values[0] : { differs_between_repetitions: values }
  }
  return out
})

writeFileSync(join(dir, 'matrix.json'), `${JSON.stringify({ run_id: recorded.run_id, fields: FIELDS, matrix }, null, 2)}\n`)
writeFileSync(join(dir, 'matrix.md'), markdown(recorded.run_id, matrix))

function derive(run) {
  const steps = run.result?.steps ?? []
  const step = (name) => steps.find((entry) => entry.step === name) ?? null
  const checkpoint = (name) => run.checkpoints.find((entry) => entry.name === name) ?? null
  const finalMarkers = run.final?.markers ?? []
  const sink = (run.final?.sink ?? []).map((row) => row.callback)
  const wroteInner = step('insert inner')?.outcome === 'returned'
  const nested = steps.some((entry) => entry.step === 'insert inner')
  const outer = (run.transactions ?? []).find((event) => event.AUTOCOMMIT === 'NO')
  const main = step('main')
  const rollbackTo = (run.statements ?? []).filter((event) => event.EVENT_NAME === 'statement/sql/rollback_to_savepoint')
  return {
    scenario: run.scenario,
    server: run.server,
    matched: run.matched_expectation,
    inner_writes: !nested ? null : wroteInner ? (finalMarkers.includes('inner') ? 'persisted' : 'rolled back') : 'not written',
    inner_after_rollback: nested ? sink.includes('afterRollBack:inner') : null,
    inner_after_commit: nested ? sink.includes('afterCommit:inner') : null,
    outer_transaction_server: outer?.STATE ?? null,
    outer_api: !main ? null : main.outcome === 'returned' ? 'returned' : `raised ${main.error.class.split('\\').pop()}`,
    rollback_to_savepoint_sent: rollbackTo.length ? rollbackTo.map((event) => (Number(event.MYSQL_ERRNO) ? `errno ${event.MYSQL_ERRNO}` : 'ok')) : 'none',
    laravel_level: run.scenario.startsWith('laravel.')
      ? {
          after_error: checkpoint('after-error')?.subject.state.laravel_transaction_level ?? null,
          after_main: main?.level_after ?? null,
          final: checkpoint('final')?.subject.state.laravel_transaction_level ?? null,
        }
      : null,
    manager_pending_after_end: checkpoint('after-end')?.subject.state.manager?.pending_levels ?? null,
    sink_final: sink,
  }
}

function markdown(runId, groupsOut) {
  const lines = [
    `# Result matrix, run ${runId}`,
    '',
    'Generated by `repro/summarize.mjs` from `runs.json`. One row per scenario and server; a value that differed between repetitions is shown as the list of values. Field sources are in `matrix.json`.',
    '',
    '| Scenario | Server | Matched | Inner writes | Inner afterRollBack | Inner afterCommit | Outer transaction (server) | Outer call | ROLLBACK TO SAVEPOINT | Laravel level: after error / after main / final | Manager pending after end | Sink, in order |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ]
  for (const row of groupsOut) {
    const level = row.laravel_level && !row.laravel_level.differs_between_repetitions
      ? `${show(row.laravel_level.after_error)} / ${show(row.laravel_level.after_main)} / ${show(row.laravel_level.final)}`
      : show(row.laravel_level)
    lines.push(`| \`${row.scenario}\` | ${row.server === 'on' ? 'ON' : 'OFF'} | ${row.matched_expectation}/${row.repetitions} | ${show(row.inner_writes)} | ${show(row.inner_after_rollback)} | ${show(row.inner_after_commit)} | ${show(row.outer_transaction_server)} | ${show(row.outer_api)} | ${show(row.rollback_to_savepoint_sent)} | ${level} | ${show(row.manager_pending_after_end)} | ${show(row.sink_final)} |`)
  }
  lines.push('', 'Server: OFF is `innodb_rollback_on_timeout=OFF` (port 13316), ON is `innodb_rollback_on_timeout=ON` (port 13317). "—" means not applicable to that scenario.', '')
  return `${lines.join('\n')}`
}

function show(value) {
  if (value === null || value === undefined) return '—'
  if (Array.isArray(value)) return value.length ? value.map((item) => `\`${item}\``).join(', ') : '(none)'
  if (typeof value === 'object') return `\`${JSON.stringify(value)}\``
  if (typeof value === 'boolean') return value ? 'yes' : 'no'
  return String(value)
}
